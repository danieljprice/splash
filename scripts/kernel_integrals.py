#!/usr/bin/env python3
#---------------------------------------------------------------
#
#  Generates the coefficient tables used by src/kernel_integrals.f90
#  to compute the exact overlap integral of an SPH kernel with
#  arbitrary polygonal (2D) or polyhedral (3D) cells, following
#  Petkova, Laibe & Bonnell (2018), J. Comp. Phys. 353, 300,
#  but generalised to any piecewise-polynomial kernel.
#
#  For each kernel W(q), normalised with cnorm, we compute
#
#   2D: G2(q) = cnorm2D int_0^q W(q') q' dq'
#   3D: G3(s) = cnorm3D int_0^s W(s') s'^2 ds'
#       A3(s) = int G3(s)/s^2 ds  (made continuous across pieces)
#
#  and print their monomial coefficients on each piece of the kernel.
#
#  Usage:
#    python3 kernel_integrals.py                 # print Fortran to stdout
#    python3 kernel_integrals.py --update FILE   # replace generated block in FILE
#    python3 kernel_integrals.py --latex         # print expanded forms in LaTeX
#
#  Kernel definitions follow phantom/scripts/kernels.py, using
#  the same radii and functional forms as splash's kernels.f90
#
#---------------------------------------------------------------
import sys
from sympy import symbols, sympify, Rational, Piecewise, integrate, expand, \
                  Poly, pi, latex, simplify, nsimplify

q, s = symbols('q s', positive=True)
maxpow = 13
begin_marker = '! --- begin generated by scripts/kernel_integrals.py ---'
end_marker   = '! --- end generated by scripts/kernel_integrals.py ---'

#--------------------------------------------------------------
# kernel definitions: list of (polynomial, upper breakpoint)
# pieces, with W = 0 beyond the last breakpoint
#--------------------------------------------------------------
def m4(R):
    return [(Rational(1,4)*(R-q)**3 - (R/2-q)**3, R/2), (Rational(1,4)*(R-q)**3, R)], 'M4 cubic'

def m5(R):
    t1 = (R-q)**4
    t2 = -5*(Rational(3,5)*R-q)**4
    t3 = 10*(Rational(1,5)*R-q)**4
    return [(t1+t2+t3, R/5), (t1+t2, Rational(3,5)*R), (t1, R)], 'M5 quartic'

def m6(R):
    t1 = (R-q)**5
    t2 = -6*(Rational(2,3)*R-q)**5
    t3 = 15*(Rational(1,3)*R-q)**5
    return [(t1+t2+t3, R/3), (t1+t2, Rational(2,3)*R), (t1, R)], 'M6 quintic'

def w2(R):
    return [((1-q/R)**4*(1+4*q/R), R)], 'Wendland C2'

def w4(R):
    return [((1-q/R)**6*(1+6*q/R+Rational(35,3)*(q/R)**2), R)], 'Wendland C4'

def w6(R):
    return [((1-q/R)**8*(1+8*q/R+25*(q/R)**2+32*(q/R)**3), R)], 'Wendland C6'

# splash kernel index -> kernel definition (see select_kernel in kernels.f90)
kernels = [(1, m4(sympify(2))), (2, m5(Rational(5,2))), (3, m6(sympify(3))),
           (4, w2(sympify(2))), (5, w4(sympify(2))), (6, w6(sympify(2)))]

#--------------------------------------------------------------
# normalisation constants in 1, 2 and 3 dimensions
#--------------------------------------------------------------
def getnorm(pieces):
    lo = 0
    i1 = i2 = i3 = 0
    for (w, qb) in pieces:
        i1 += integrate(w, (q, lo, qb))
        i2 += integrate(2*pi*q*w, (q, lo, qb))
        i3 += integrate(4*pi*q*q*w, (q, lo, qb))
        lo = qb
    return (simplify(1/(2*i1)), simplify(1/i2), simplify(1/i3))

#--------------------------------------------------------------
# piecewise cumulative integral int_0^x f(x') dx', continuous
# across the breakpoints; returns a list of expressions in x,
# one per piece plus one for the region beyond the kernel
#--------------------------------------------------------------
def cumulative(pieces, f, x):
    out = []
    lo = 0
    total = 0
    for (w, qb) in pieces:
        g = integrate(f(w.subs(q, x), x), x)
        g = expand(g - g.subs(x, lo) + total)
        out.append(g)
        total = g.subs(x, qb)
        lo = qb
    out.append(total)
    return out

#--------------------------------------------------------------
# antiderivative of G3/s^2 on each piece, with constants chosen
# so that the result is continuous across the breakpoints
#--------------------------------------------------------------
def get_A3(pieces, G3):
    out = []
    offset = 0
    for j, g in enumerate(G3):
        a = expand(integrate(expand(g/s**2), s))
        if j > 0:
            qb = pieces[j-1][1]
            offset = expand(out[j-1].subs(s, qb) - a.subs(s, qb))
        out.append(expand(a + offset))
    return out

#--------------------------------------------------------------
# coefficient of s^n (n may be negative) in a Laurent polynomial
#--------------------------------------------------------------
def coeffs(expr, x, nmin):
    p = Poly(expand(expr*x**(-nmin)), x)
    c = {}
    for (k,), v in p.terms():
        if v != 0:
            c[k + nmin] = v
    return c

def get_tables(pieces):
    c1, c2, c3 = getnorm(pieces)
    G2 = cumulative(pieces, lambda w, x: c2*w*x, q)
    G3 = cumulative(pieces, lambda w, x: c3*w*x*x, s)
    A3 = get_A3(pieces, G3)
    return (c1, c2, c3), G2, G3, A3

#--------------------------------------------------------------
# format a rational number as a Fortran double precision literal
#--------------------------------------------------------------
def fdbl(v):
    return repr(float(v)).replace('e', 'd') if 'e' in repr(float(v)) else repr(float(v)) + 'd0'

def print_fortran():
    lines = []
    lines.append(begin_marker)
    lines.append('!' + '-'*71)
    lines.append('!+')
    lines.append('!  Coefficient tables for each kernel (see header of this module)')
    lines.append('!  DO NOT EDIT: regenerate with scripts/kernel_integrals.py')
    lines.append('!+')
    lines.append('!' + '-'*71)
    lines.append('subroutine get_kernel_integral_coeffs(ikern,npieces,nmax,qb,g2,a3)')
    lines.append(' integer,  intent(in)  :: ikern')
    lines.append(' integer,  intent(out) :: npieces,nmax')
    lines.append(' real(dp), intent(out) :: qb(maxpieces),g2(-1:maxpow,maxpieces+1)')
    lines.append(' real(dp), intent(out) :: a3(-1:maxpow,maxpieces+1)')
    lines.append('')
    lines.append(' qb = 0._dp')
    lines.append(' g2 = 0._dp')
    lines.append(' a3 = 0._dp')
    lines.append(' select case(ikern)')
    for (ik, (pieces, name)) in reversed(kernels):
        norms, G2, G3, A3 = get_tables(pieces)
        nmax = 0
        if ik == 1:
            lines.append(' case default ! ' + name)
        else:
            lines.append(' case(%i) ! %s' % (ik, name))
        lines.append('    npieces = %i' % len(pieces))
        for j, (w, qb) in enumerate(pieces):
            lines.append('    qb(%i) = %s' % (j+1, fdbl(qb)))
        for j in range(len(pieces)+1):
            for n, v in sorted(coeffs(G2[j], q, 0).items()):
                lines.append('    g2(%i,%i) = %s' % (n, j+1, fdbl(v)))
                nmax = max(nmax, n)
            for n, v in sorted(coeffs(A3[j], s, -1).items()):
                assert n != 1, 'unexpected s^1 term in A3'
                lines.append('    a3(%i,%i) = %s' % (n, j+1, fdbl(v)))
                nmax = max(nmax, n)
        assert nmax <= maxpow, 'increase maxpow'
        lines.append('    nmax = %i' % nmax)
    lines.append(' end select')
    lines.append('')
    lines.append('end subroutine get_kernel_integral_coeffs')
    lines.append(end_marker)
    return '\n'.join(lines)

#--------------------------------------------------------------
# LaTeX output of the fully expanded forms for each kernel
#--------------------------------------------------------------
def piecewise_tex(exprs, pieces, x):
    rows = []
    lo = 0
    for j, e in enumerate(exprs):
        if j < len(pieces):
            cond = r'%s \le %s < %s' % (latex(lo), latex(x), latex(pieces[j][1]))
            lo = pieces[j][1]
        else:
            cond = r'%s \ge %s' % (latex(x), latex(lo))
        rows.append(r'%s, & %s' % (latex(e), cond))
    return r'\begin{cases}' + r' \\ '.join(rows) + r'\end{cases}'

def vertex_tex(expr, x, nmin, sym):
    terms = []
    for n, v in sorted(coeffs(expr, x, nmin).items()):
        if n == -1:
            terms.append(r'%s\,T' % latex(v))
        else:
            terms.append(r'%s\,%s_{%i}' % (latex(v), sym, n))
    return ' + '.join(terms).replace('+ -', '- ')

def print_latex():
    out = []
    for (ik, (pieces, name)) in kernels:
        (c1, c2, c3), G2, G3, A3 = get_tables(pieces)
        W = [w for (w, qb) in pieces] + [sympify(0)]
        out.append(r'\subsection*{%s (kernel %i)}' % (name, ik))
        out.append(r'Normalisation: $C_{1D} = %s$, $C_{2D} = %s$, $C_{3D} = %s$.' % (latex(c1), latex(c2), latex(c3)))
        out.append(r'\begin{equation}')
        out.append(r'w(q) = ' + piecewise_tex([expand(w) for w in W], pieces, q))
        out.append(r'\end{equation}')
        out.append(r'\begin{equation}')
        out.append(r'G_{2}(q) = ' + piecewise_tex(G2, pieces, q))
        out.append(r'\end{equation}')
        out.append(r'\begin{equation}')
        out.append(r'G_{3}(s) = ' + piecewise_tex(G3, pieces, s))
        out.append(r'\end{equation}')
        out.append(r'\begin{equation}')
        out.append(r'A_{3}(s) = ' + piecewise_tex(A3, pieces, s))
        out.append(r'\end{equation}')
        out.append(r'Vertex integrals on each piece $j$, with $\Delta$ the difference between the ends of each sub-interval in $\phi$:')
        out.append(r'\begin{align}')
        rows = []
        for j in range(len(pieces)+1):
            rows.append(r'V_{2}^{(%i)} &= \Delta\left[%s\right] \\' % (j+1, vertex_tex(G2[j], q, 0, 'S')))
        for j in range(len(pieces)+1):
            rows.append(r'V_{3}^{(%i)} &= \Delta\left[%s\right] \\' % (j+1, vertex_tex(A3[j]*s, s, 0, r'\tilde{S}')))
        rows[-1] = rows[-1].rstrip('\\ ')
        out.extend(rows)
        out.append(r'\end{align}')
        out.append('')
    return '\n'.join(out)

#--------------------------------------------------------------
# replace the generated block in an existing Fortran file
#--------------------------------------------------------------
def update_file(filename):
    with open(filename) as f:
        text = f.read()
    i1 = text.index(begin_marker)
    i2 = text.index(end_marker) + len(end_marker)
    text = text[:i1] + print_fortran() + text[i2:]
    with open(filename, 'w') as f:
        f.write(text)

if __name__ == '__main__':
    if '--latex' in sys.argv:
        print(print_latex())
    elif '--update' in sys.argv:
        update_file(sys.argv[sys.argv.index('--update')+1])
    elif '--check' in sys.argv:
        for (ik, (pieces, name)) in kernels:
            c = getnorm(pieces)
            print(ik, name, c, [float(x) for x in c])
    else:
        print(print_fortran())
